#!/usr/bin/env python3
"""params.lock + vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/VavraPlugin.cpp).

params.lock is the FROZEN VST order of the released 0.1.0 wrapper build (583 indices, read out of its vavra.so by
tools/released_params.py into vst/released-0.1.0.tsv): the 437 keys of vst/params.json, then the 146 hidden "<key>__open" flags that
build added, one per popup of vst/layout.conf. Saved projects, automation and Q-Link assignments bind to these indices. This build keeps
them: index 437 is ui_open (0 = closed, k + 1 = the pick-list of the k-th popup in params.lock), 438..582 are inert reserved slots, and
new parameters are only ever APPENDED (add them to APPENDED below and to params.lock).

The released ranges are checked too: every engine value and choice keeps its min, max, default and option count (readouts, tiles and
momentary keys carry no value a project could depend on, so their SDK ranges may differ).
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "params.lock")) if l.strip()]
REL = [l.rstrip("\n").split("\t") for l in open(os.path.join(ROOT, "vst", "released-0.1.0.tsv")) if l.strip()]
NPOP = 146
KB_CHARS = "1234567890QWERTYUIOPASDFGHJKLZXCVBNM-"
APPENDED = [                     # (key, name, min, max, default, flags) appended after the released 583, in this order
    ("random_patch", "RANDOM", 0, 1, 0, 1 | 512),      # kMomentary | kNoAuto: the engine's verb, a random sound from every loaded bank (BANKS page)
    # the naming keyboard for +FAV (Profit-5's): the typed name (a text readout), the keyboard's visibility, its keys (kLocal)
    ("fav_name", "Favourite Name", 0, 1023, 0, 2 | 4096 | 512),
    ("kb_open", "Keyboard", 0, 1, 0, 16 | 4096 | 512),
] + [("kb_" + ("dash" if c == "-" else c.lower()), "Key " + c, 0, 1, 0, 1 | 4096 | 512) for c in KB_CHARS] + [
    ("kb_space", "Key Space", 0, 1, 0, 1 | 4096 | 512), ("kb_bksp", "Key Delete", 0, 1, 0, 1 | 4096 | 512),
    ("kb_shift", "Key Shift", 0, 1, 0, 1 | 4096 | 512), ("kb_cancel", "Key Cancel", 0, 1, 0, 1 | 4096 | 512),
    ("kb_save", "Key Save", 0, 1, 0, 1 | 4096 | 512),
    # the skin switch (Xenia's): 0 the microQ look, 1 the alternative theme (to come). kLocal: one setting for the whole MPC
    # (<plugin folder>/vavra-skin.txt), a project load leaves it alone
    ("skin", "Skin", 0, 1, 0, 4096 | 512),
]

keys = [p["key"] for p in P]
popups = [k[:-len("__open")] for k in LOCK[len(keys):len(keys) + NPOP]]
expect = keys + [k + "__open" for k in popups] + [a[0] for a in APPENDED]
if LOCK != expect:
    for i, (a, b) in enumerate(zip(LOCK, expect)):
        if a != b:
            sys.exit("params.lock index %d is %s, the table gives %s: the order is frozen (append only)" % (i, a, b))
    sys.exit("params.lock has %d entries, the table gives %d: the order is frozen (append only)" % (len(LOCK), len(expect)))
if [r[0] for r in REL] != LOCK[:len(REL)]:
    sys.exit("params.lock does not start with the released table (vst/released-0.1.0.tsv)")
if not all(k in keys for k in popups):
    sys.exit("a popup in params.lock is not an engine key")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kMomentary=1, kText=2, kChoice=8, kUi=16, kReserved=32, kStep=128, kTile=256, kNoAuto=512, kPolled=1024,
          kRefresh=2048, kLocal=4096)
out = ["/* generated by tools/gen_sdk_params.py from params.lock + vst/params.json: do not edit. One row per parameter, frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


def row(key, name, lo, hi, d, fl, ch="nullptr", n=0, st=-1, sd=0.0):
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(key), json.dumps(name), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))


def check(i, k, lo, hi, d, n):
    """an engine value must keep the released range and (normalised) default"""
    _, rlo, rhi, rdef, rn = REL[i]
    rlo, rhi, rdef, rn = float(rlo), float(rhi), float(rdef), int(rn)
    if n:
        ok = rn == n and abs(rdef - (d / (n - 1) if n > 1 else 0)) < 1e-4
    else:
        ok = rn == 0 and rlo == lo and rhi == hi and abs(rdef - ((d - lo) / (hi - lo) if hi > lo else 0)) < 1e-4
    if not ok:
        sys.exit("%s (index %d) differs from the released table: %s vs min %g max %g def %g options %d" % (k, i, REL[i][1:], lo, hi, d, n))


for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if "options" in p:
        opts = p["options"]
        fl |= FL["kChoice"] | FL["kPolled"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        d = opts.index(p["default"]) if isinstance(p["default"], str) else p["default"]
        lo, hi = 0, len(opts) - 1
        check(i, k, lo, hi, d, n)
    else:
        lo, hi, d = p.get("min", 0), p.get("max", 1), p.get("default", 0)
        if k.startswith("bank_slot_") or k.startswith("patch_slot_"):
            fl |= FL["kMomentary"] | FL["kText"] | FL["kTile"] | FL["kNoAuto"]      # list tiles: tap = pick, lit = "<key>_on"
            lo, hi = 0, 1
        elif p.get("momentary"):
            fl |= FL["kMomentary"] | FL["kNoAuto"]
            lo, hi = 0, 1
            if p.get("step_of"):
                fl |= FL["kStep"]
                st, sd = idx[p["step_of"]], p.get("step_delta", 1)
        elif p.get("display") == "string":
            fl |= FL["kText"] | FL["kNoAuto"]                                        # readouts: the value is a change counter
            lo, hi, d = 0, 1023, 0
        else:
            fl |= FL["kPolled"]
            check(i, k, lo, hi, d, 0)
    if k in ("bank_index", "preset", "favourite"):
        fl |= FL["kNoAuto"]
    row(k, p["name"], lo, hi, d, fl, ch, n, st, sd)

row("ui_open", "Pick List", 0, len(popups), 0, FL["kUi"] | FL["kNoAuto"])
for j in range(1, len(popups)):
    row("rsv_%d" % (len(P) + j), "Reserved %d" % j, 0, 1, 0, FL["kReserved"] | FL["kNoAuto"])
for a in APPENDED:
    row(*a)

out += ["static const char *const g_popups[] = {%s};" % ", ".join(json.dumps(k) for k in popups)]
out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % len(LOCK),
        "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's keys" % len(P),
        "static const int kUiParam = %d;            // ui_open: 0 closed, k + 1 = pick-list of g_popups[k]" % len(P),
        "static const int kNumPopups = %d;" % len(popups),
        "static const int kFirstAppended = %d;" % (len(keys) + NPOP),
        "static const int kFavParam = %d;           // \"favourite\": the PRESET menu's program (VST programs = favourites)" % idx["favourite"],
        "static const int kFavSlots = 64;",
        "static const int kFavSave = %d;            // +FAV (0.1.0's fav_save): opens the naming keyboard" % idx["fav_save"],
        "static const int kFavName = %d, kKbOpen = %d, kKbFirst = %d, kKbCount = %d;" % (LOCK.index("fav_name"), LOCK.index("kb_open"),
                                                                                      LOCK.index("kb_1"), len(KB_CHARS) + 5),
        "static const char kKbChars[] = %s;   // the character keys from kKbFirst, then space, delete, shift, cancel, save" % json.dumps(KB_CHARS),
        "static const int kFavNameMax = 20;",
        "static const int kSkin = %d;               // the skin switch (kLocal, global)" % LOCK.index("skin"), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params (%d engine, ui_open, %d reserved, %d appended)" % (len(LOCK), len(P), len(popups) - 1, len(APPENDED)))
